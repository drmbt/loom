"""Generate the fixture-decode point kernels for a show's patch (VN131).

The stage previz decodes DMX into light with two Point Kernels whose `field` input is a DMX
texture (512 x 128, row = universe - 1, red = slot / 255): today `ma3ShowIn`'s output, later an
Art-Net or sACN input with the same layout. The kernels know the patch (where each fixture
is, which way it faces, its universe and address, its type) as constant tables generated
here from a show package, so the same kernels decode the show file and a live console alike.

    python3 tools/ma3/gen_fixture_kernels.py public/media/stage-previz/ma3/twentyfiveeight.ma3show.json \
        > projects/stage-previz/ma3/fixture-kernels.json

Kernel `cells`: one point per emitter cell of the pixel bars and bursts (Instances, quad,
tint/orient per point). Kernel `heads`: two points per moving head or colour strobe: role 0
the beam (Beam mode, `tip` endpoint), role 1 the lens (Points mode).
Positions: the package's previz frame (Blender: Z up, audience -Y) mapped to Loom's (x, z, -y).
"""

import json
import math
import sys

BAR_CELLS, BURST_CELLS = 48, 24
TYPE_IDS = {  # heads kernel decode branch per profile
    "Martin Mac Aura XB@Standard - RGB": 0,
    "Elation Proteus Lucius@Standard": 1,
    "Robe Robin iForte FS@Mode 1 - Standard 16 bit": 2,
    "Robe Robin ColorStrobe@Mode 1": 3,
}


def loom(v):
    return (v[0], v[2], -v[1])


def f(x):
    return f"{x:.5f}"


def v3(v):
    return f"vec3f({f(v[0])}, {f(v[1])}, {f(v[2])})"


DMX_HELPERS = """
/* The DMX texture: 512 slots x 128 universes, red = byte / 255. fieldAt maps clip xy to the
   texel the Texture To Attribute bridge would read; aim a quarter texel in so floor() lands. */
fn dmxAt(slot: u32) -> f32 {
  let c = f32(slot % 512u);
  let r = f32(slot / 512u);
  return fieldAt(vec3f((c + 0.25) / 511.0 * 2.0 - 1.0, 1.0 - (r + 0.25) / 127.0 * 2.0, 0.0)).r;
}
fn dmx16(slot: u32) -> f32 {
  return (floor(dmxAt(slot) * 255.0 + 0.5) * 256.0 + floor(dmxAt(slot + 1u) * 255.0 + 0.5)) / 65535.0;
}
"""


def cells_kernel(bars, bursts):
    n = len(bars) + len(bursts)
    base = ", ".join(f"{fx['_slot']}u" for fx in bars + bursts)
    pos = ",\n  ".join(v3(loom(fx["position"])) for fx in bars + bursts)
    ax_u = ",\n  ".join(v3(loom(fx["axes"][0])) for fx in bars + bursts)
    ax_v = ",\n  ".join(v3(loom(fx["axes"][1])) for fx in bars + bursts)
    ax_w = ",\n  ".join(v3(loom(fx["axes"][2])) for fx in bars + bursts)
    nb = len(bars)
    return f"""// VN131 — pixel bar and burst cells decoded from DMX (generated by tools/ma3/gen_fixture_kernels.py).
// @use quat
struct Params {{
  gain: f32, // @default 3  Light out for a cell at full: the emissive multiplier.
  floorLevel: f32, // @default 0.02  What a dark cell still shows, so the bars read when off.
}};
{DMX_HELPERS}
const FIXTURES: u32 = {n}u;
const BARS: u32 = {nb}u;
const BASE: array<u32, {n}> = array<u32, {n}>({base});
const POS: array<vec3f, {n}> = array<vec3f, {n}>(
  {pos});
const AU: array<vec3f, {n}> = array<vec3f, {n}>(
  {ax_u});
const AV: array<vec3f, {n}> = array<vec3f, {n}>(
  {ax_v});
const AW: array<vec3f, {n}> = array<vec3f, {n}>(
  {ax_w});

fn process(p: Point, ctx: PointCtx) -> Point {{
  var q = p;
  let i = ctx.index;
  var fx: u32;
  var c: u32;
  if (i < BARS * {BAR_CELLS}u) {{ fx = i / {BAR_CELLS}u; c = i % {BAR_CELLS}u; }}
  else {{ let j = i - BARS * {BAR_CELLS}u; fx = BARS + j / {BURST_CELLS}u; c = j % {BURST_CELLS}u; }}
  if (fx >= FIXTURES) {{ q.tint = vec4f(0.0); q.size = 0.0; return q; }}
  let b = BASE[fx];
  var local = vec2f(0.0);   // along u, along v (metres)
  var size = 0.03;
  var light = vec3f(0.0);
  if (fx < BARS) {{
    // Acme Pixel Line IP, Mode 10: ch1 master; RGB cell k at 6+3(k-1); white cell k at 101+k.
    let master = dmxAt(b);
    if (c < 32u) {{
      let o = b + 5u + 3u * c;
      light = vec3f(dmxAt(o), dmxAt(o + 1u), dmxAt(o + 2u)) * master;
      local = vec2f(-0.5 + (f32(c) + 0.5) / 32.0, -0.016);
      size = 0.029;
    }} else {{
      let k = c - 32u;
      light = vec3f(dmxAt(b + 101u + k)) * master;
      local = vec2f(-0.5 + (f32(k) + 0.5) / 16.0, 0.016);
      size = 0.03;
    }}
  }} else {{
    // GLP JDC Burst 1, Mode 3: RGBW pixel k at 40+4(k-1) under the pixel master (24-25), the
    // RGBW module (11-12 dimmer, 16-19 colour) over all of it; white pixel k at 27+k under the
    // white pixel master (20-21), the white module (6-7) over all of it. Layers combine HTP.
    if (c < 12u) {{
      let o = b + 39u + 4u * c;
      let w = dmxAt(o + 3u);
      let cell = (vec3f(dmxAt(o), dmxAt(o + 1u), dmxAt(o + 2u)) + vec3f(w)) * dmx16(b + 23u);
      let mw = dmxAt(b + 18u);
      let whole = (vec3f(dmxAt(b + 15u), dmxAt(b + 16u), dmxAt(b + 17u)) + vec3f(mw)) * dmx16(b + 10u);
      light = max(cell, whole);
      local = vec2f(-0.15 + 0.06 * f32(c % 6u), select(0.045, -0.045, c < 6u));
      size = 0.055;
    }} else {{
      let k = c - 12u;
      light = vec3f(max(dmxAt(b + 27u + k) * dmx16(b + 19u), dmx16(b + 5u)));
      local = vec2f(-0.165 + 0.03 * f32(k), 0.0);
      size = 0.028;
    }}
  }}
  let u = AU[fx];
  let v = AV[fx];
  let w = AW[fx];
  // Cells sit on the face the light leaves from (-w), a little proud of the body.
  q.position = POS[fx] + u * local.x + v * local.y - w * 0.06;
  // (u, -v, -w) keeps the frame right-handed with the quad facing out of the light's face.
  q.orient = quatFromFrame(u, -v, -w);
  q.size = size;
  q.tint = vec4f(max(light * ctx.params.gain, vec3f(ctx.params.floorLevel)), 1.0);
  return q;
}}
"""


def heads_kernel(heads, deck_y):
    n = len(heads)
    base = ", ".join(f"{fx['_slot']}u" for fx in heads)
    kinds = ", ".join(f"{TYPE_IDS[fx['type']]}u" for fx in heads)
    pos = ",\n  ".join(v3(loom(fx["position"])) for fx in heads)
    ax_u = ",\n  ".join(v3(loom(fx["axes"][0])) for fx in heads)
    ax_v = ",\n  ".join(v3(loom(fx["axes"][1])) for fx in heads)
    ax_w = ",\n  ".join(v3(loom(fx["axes"][2])) for fx in heads)
    return f"""// VN131 — moving heads and colour strobes decoded from DMX (generated by tools/ma3/gen_fixture_kernels.py).
// Two points per head: role 0 the beam (position = lens, tip = where it lands), role 1 the lens.
struct Params {{
  beamGain: f32, // @default 0.35  Beam brightness: haze density, in effect.
  lensGain: f32, // @default 4  Lens brightness.
  reach: f32, // @default 18  Longest beam, metres, when it lands on nothing.
}};
{DMX_HELPERS}
const HEADS: u32 = {n}u;
const DECK_Y: f32 = {f(deck_y)};
const PI: f32 = 3.14159265358979;
const BASE: array<u32, {n}> = array<u32, {n}>({base});
const KIND: array<u32, {n}> = array<u32, {n}>({kinds});
const POS: array<vec3f, {n}> = array<vec3f, {n}>(
  {pos});
const AU: array<vec3f, {n}> = array<vec3f, {n}>(
  {ax_u});
const AV: array<vec3f, {n}> = array<vec3f, {n}>(
  {ax_v});
const AW: array<vec3f, {n}> = array<vec3f, {n}>(
  {ax_w});

fn process(p: Point, ctx: PointCtx) -> Point {{
  var q = p;
  let h = ctx.index / 2u;
  let role = ctx.index % 2u;
  q.role = f32(role);
  if (h >= HEADS) {{ q.tint = vec4f(0.0); q.width = 0.0; q.tip = q.position; return q; }}
  let b = BASE[h];
  var pan = 0.0;
  var tilt = 0.0;
  var zoom = 40.0;   // full beam angle, degrees
  var colour = vec3f(1.0);
  var dim = 0.0;
  switch KIND[h] {{
    case 0u: {{   // Mac Aura XB, Standard (14): 2 dim, 3 zoom 53->11, 4-5 pan, 6-7 tilt, 10-12 RGB
      dim = dmxAt(b + 1u);
      zoom = mix(53.0, 11.0, dmxAt(b + 2u));
      pan = mix(-270.0, 270.0, dmx16(b + 3u));
      tilt = mix(-116.0, 116.0, dmx16(b + 5u));
      colour = vec3f(dmxAt(b + 9u), dmxAt(b + 10u), dmxAt(b + 11u));
    }}
    case 1u: {{   // Proteus Lucius, Standard (43): 1-2 pan, 3-4 tilt, 5-7 CMY, 23-24 zoom, 26-27 dim
      pan = mix(-270.0, 270.0, dmx16(b));
      tilt = mix(-125.0, 125.0, dmx16(b + 2u));
      colour = vec3f(1.0) - vec3f(dmxAt(b + 4u), dmxAt(b + 5u), dmxAt(b + 6u));
      zoom = mix(5.5, 50.0, dmx16(b + 22u));
      dim = dmx16(b + 25u);
    }}
    case 2u: {{   // iForte FS, Mode 1 (54): 1-2 pan, 3-4 tilt, 14-16 CMY, 39-40 zoom 55->5, 53-54 dim
      pan = mix(-270.0, 270.0, dmx16(b));
      tilt = mix(-135.0, 135.0, dmx16(b + 2u));
      colour = vec3f(1.0) - vec3f(dmxAt(b + 13u), dmxAt(b + 14u), dmxAt(b + 15u));
      zoom = mix(55.0, 5.0, dmx16(b + 38u));
      dim = dmx16(b + 52u);
    }}
    default: {{   // ColorStrobe, Mode 1 (9): 1-4 RGBW, 7 dim; a fixed wide flood
      colour = vec3f(dmxAt(b), dmxAt(b + 1u), dmxAt(b + 2u)) + vec3f(dmxAt(b + 3u));
      dim = dmxAt(b + 6u);
      zoom = 70.0;
    }}
  }}
  // GDTF: the beam leaves along local -Z at pan = tilt = 0; tilt turns about local X, pan about local Z.
  let pr = radians(pan);
  let tr = radians(tilt);
  let dl = vec3f(-sin(tr) * sin(pr), sin(tr) * cos(pr), -cos(tr));
  let dir = normalize(AU[h] * dl.x + AV[h] * dl.y + AW[h] * dl.z);
  var reach = ctx.params.reach;
  if (KIND[h] == 3u) {{ reach = 4.0; }}
  if (dir.y < -0.01) {{ reach = min(reach, (POS[h].y - DECK_Y) / -dir.y); }}
  let light = colour * dim;
  q.position = POS[h] + dir * 0.18;
  if (role == 0u) {{
    q.tip = q.position + dir * reach;
    q.width = reach * tan(radians(zoom) * 0.5);
    // A wide beam spreads the same light: a flood reads soft, a narrow beam reads as a shaft.
    q.tint = vec4f(light * ctx.params.beamGain * clamp(14.0 / zoom, 0.12, 1.6), 1.0);
  }} else {{
    q.tip = q.position;
    q.width = select(0.12, 0.3, KIND[h] == 3u);
    q.tint = vec4f(light * ctx.params.lensGain, 1.0);
  }}
  return q;
}}
"""


def main():
    show = json.load(open(sys.argv[1]))
    deck_z = float(sys.argv[2]) if len(sys.argv) > 2 else 1.524
    for fx in show["fixtures"]:
        fx["_slot"] = (fx["universe"] - 1) * 512 + fx["address"] - 1
    bars = [fx for fx in show["fixtures"] if fx["kind"] == "pixelbar"]
    bursts = [fx for fx in show["fixtures"] if fx["kind"] == "burst"]
    heads = [fx for fx in show["fixtures"] if fx["kind"] in ("mover", "strobe")]
    out = dict(
        cells=dict(capacity=len(bars) * BAR_CELLS + len(bursts) * BURST_CELLS, kernel=cells_kernel(bars, bursts),
                   attributes=[{"name": "position", "type": "vec3f", "semantic": "position", "default": [0, 0, 0]},
                               {"name": "tint", "type": "vec4f", "semantic": "color", "qualifier": "color", "default": [0, 0, 0, 1]},
                               {"name": "orient", "type": "vec4f", "default": [0, 0, 0, 1]},
                               {"name": "size", "type": "f32", "default": [0.03]}]),
        heads=dict(capacity=len(heads) * 2, kernel=heads_kernel(heads, deck_z),
                   attributes=[{"name": "position", "type": "vec3f", "semantic": "position", "default": [0, 0, 0]},
                               {"name": "tip", "type": "vec3f", "default": [0, 0, 0]},
                               {"name": "tint", "type": "vec4f", "semantic": "color", "qualifier": "color", "default": [0, 0, 0, 1]},
                               {"name": "width", "type": "f32", "default": [0.1]},
                               {"name": "role", "type": "f32", "default": [0]}]),
        counts=dict(bars=len(bars), bursts=len(bursts), heads=len(heads)),
    )
    json.dump(out, sys.stdout, indent=1)


if __name__ == "__main__":
    main()
